#!/usr/bin/env python3
"""Generate load-testing Zone, DNSEndpoint and optional Location resources for EdgeCDN-X.

Each zone gets a random number of A, AAAA and CNAME records, bounded by the
--min-records / --max-records options. By default the bounds apply per record
type; with --total they apply to the total number of records per zone, randomly
split between A, AAAA and CNAME.
With --routing-policy Weighted or Geolocation, generate only A/AAAA endpoints,
each with its own locations. Geolocation also exercises node-group selectors.

Examples:
  # Print manifests for 10 zones, 1-20 records of each type per zone
  ./generate_zones.py --zones 10 --min-records 1 --max-records 20

  # Write to a file
  ./generate_zones.py --zones 100 --max-records 50 -o load.yaml

  # Apply directly to the cluster
  ./generate_zones.py --zones 100 --max-records 50 --apply

  # Remove everything previously generated by this script
  ./generate_zones.py --delete
"""

import argparse
import ipaddress
import json
import random
import subprocess
import sys

API_VERSION = "infrastructure.edgecdnx.com/v1alpha1"
LABEL_KEY = "profiler.edgecdnx.com/generated"
RECORD_TYPES = ("A", "AAAA", "CNAME")


def add_wrr_options(parser):
    parser.add_argument("--location-weights", default="1,2,3",
                        help="Comma-separated weights, cycled across each endpoint's locations (default: 1,2,3)")
    parser.add_argument("--locations-per-endpoint", type=int,
                        help="Locations per dynamic endpoint (default: number of --location-weights)")
    parser.add_argument("--nodes-per-location", type=int, default=1,
                        help="Dual-stack nodes per location (per group for Geolocation; default: 1)")
    parser.add_argument("--routing-instance", default="edgecdnx",
                        help="Routing-instance label on generated locations (default: edgecdnx)")


def validate_wrr_options(parser, args):
    try:
        args.location_weights = [int(weight) for weight in args.location_weights.split(",")]
    except ValueError:
        parser.error("--location-weights must be comma-separated integers")
    if not args.location_weights or any(weight < 0 or weight > 2147483647 for weight in args.location_weights):
        parser.error("--location-weights must be in [0, 2147483647]")
    if not any(args.location_weights):
        parser.error("--location-weights must include a positive weight")
    if args.locations_per_endpoint is None:
        args.locations_per_endpoint = len(args.location_weights)
    if args.locations_per_endpoint < 1:
        parser.error("--locations-per-endpoint must be >= 1")
    if not any(args.location_weights[:args.locations_per_endpoint]):
        parser.error("the weights used by each endpoint must include a positive weight")
    if args.nodes_per_location < 1:
        parser.error("--nodes-per-location must be >= 1")


def add_geo_options(parser):
    parser.add_argument("--node-groups-per-location", type=int, default=4,
                        help="Node groups per GeoLookup location; only the last matches (default: 4)")
    parser.add_argument("--geo-attribute", default="geoip/continent/code",
                        help="Metadata attribute used for GeoLookup scoring (default: geoip/continent/code)")
    parser.add_argument("--geo-values", default="EU,NA,AS",
                        help="Comma-separated metadata values cycled across locations (default: EU,NA,AS)")


def validate_geo_options(parser, args):
    if args.node_groups_per_location < 1:
        parser.error("--node-groups-per-location must be >= 1")
    if any(weight > 1000 for weight in args.location_weights):
        parser.error("Geolocation --location-weights must be in [0, 1000]")
    if "/" not in args.geo_attribute or any(not part for part in args.geo_attribute.split("/")):
        parser.error("--geo-attribute must be a metadata label such as geoip/continent/code")
    args.geo_values = [value.strip() for value in args.geo_values.split(",")]
    if not all(args.geo_values):
        parser.error("--geo-values must be comma-separated nonempty values")

# Documentation ranges (RFC 5737 / RFC 3849) so generated records never point at real hosts.
IPV4_NETS = [ipaddress.ip_network(n) for n in ("192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24")]
IPV6_NET = ipaddress.ip_network("2001:db8::/32")


def parse_args():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("-z", "--zones", type=int, help="Number of zones to create")
    p.add_argument("--min-records", type=int, default=1,
                   help="Minimum number of records of each type (A/AAAA/CNAME) per zone (default: 1)")
    p.add_argument("--max-records", type=int, default=10,
                   help="Maximum number of records of each type (A/AAAA/CNAME) per zone (default: 10)")
    p.add_argument("--total", action="store_true",
                   help="Apply --min-records/--max-records to the total records per zone instead of per type")
    p.add_argument("--name-width", type=int, default=4,
                   help="Minimum zero-padded width of the zone number (default: 4)")
    p.add_argument("--max-targets", type=int, default=3,
                   help="Maximum number of targets per A/AAAA record (default: 3)")
    p.add_argument("-n", "--namespace", default="edgecdnx", help="Target namespace (default: edgecdnx)")
    p.add_argument("--zone-suffix", default="profiler.test",
                   help="Parent domain for generated zones (default: profiler.test)")
    p.add_argument("--zone-prefix", default="zone", help="Prefix for zone labels (default: zone)")
    p.add_argument("--ttl", type=int, default=60, help="Record TTL in seconds (default: 60)")
    p.add_argument("--seed", type=int, help="Random seed for reproducible output")
    p.add_argument("-o", "--output", help="Write manifests to this file instead of stdout")
    p.add_argument("--apply", action="store_true", help="Pipe manifests to 'kubectl apply -f -'")
    p.add_argument("--delete", action="store_true",
                   help=f"Delete all Zones/DNSEndpoints/Locations labelled {LABEL_KEY}=true and exit")
    p.add_argument("--kubeconfig", help="Kubeconfig file to pin kubectl to (independent of the active context in other terminals)")
    p.add_argument("--context", help="kubectl context within the selected kubeconfig")
    p.add_argument("--routing-policy", choices=("Simple", "Weighted", "Geolocation"), default="Simple",
                   help="Endpoint routing policy; Weighted and Geolocation also generate locations")
    add_wrr_options(p)
    add_geo_options(p)
    args = p.parse_args()

    if args.delete:
        return args
    if args.zones is None:
        p.error("--zones is required")
    if args.zones < 1:
        p.error("--zones must be >= 1")
    if args.min_records < 0 or args.max_records < args.min_records:
        p.error("require 0 <= --min-records <= --max-records")
    if args.max_targets < 1:
        p.error("--max-targets must be >= 1")
    if args.apply and args.output:
        p.error("--apply and --output are mutually exclusive")
    validate_wrr_options(p, args)
    if args.routing_policy == "Geolocation":
        validate_geo_options(p, args)
    return args


def random_ipv4(rng):
    net = rng.choice(IPV4_NETS)
    return str(net[rng.randint(1, net.num_addresses - 2)])


def random_ipv6(rng):
    return str(IPV6_NET[rng.randint(1, 2**64)])


def zone_manifest(name, zone, namespace):
    return (
        "---\n"
        f"apiVersion: {API_VERSION}\n"
        "kind: Zone\n"
        "metadata:\n"
        f"  name: {name}\n"
        f"  namespace: {namespace}\n"
        "  labels:\n"
        f"    {LABEL_KEY}: \"true\"\n"
        "spec:\n"
        f"  zone: {zone}\n"
        f"  email: noc.{zone}.\n"
    )


def endpoint_manifest(name, namespace, zone_name, dns_name, record_type, ttl, targets,
                      routing_policy="Simple"):
    targets_yaml = "".join(f"    - \"{t}\"\n" for t in targets)
    return (
        "---\n"
        f"apiVersion: {API_VERSION}\n"
        "kind: DNSEndpoint\n"
        "metadata:\n"
        f"  name: {name}\n"
        f"  namespace: {namespace}\n"
        "  labels:\n"
        f"    {LABEL_KEY}: \"true\"\n"
        f"    profiler.edgecdnx.com/zone: {zone_name}\n"
        "spec:\n"
        f"  dnsName: {dns_name}\n"
        f"  routingPolicy: {routing_policy}\n"
        f"  recordTTL: {ttl}\n"
        f"  recordType: {record_type}\n"
        + (f"  routeSelector:\n    matchLabels:\n      zone: {zone_name}\n      dnsendpoint: {name}\n"
           + ('      profiler.edgecdnx.com/node-group: "selected"\n'
              if routing_policy == "Geolocation" else "")
           if routing_policy in ("Weighted", "Geolocation") else "  targets:\n" + targets_yaml)
    )


def location_manifest(args, index, weight, zone_name, endpoint_name):
    if len(zone_name) > 63 or len(endpoint_name) > 63:
        raise ValueError("WRR zone and endpoint names must fit Kubernetes label values (63 characters)")
    name = f"{endpoint_name}-wrr-{index:04d}"
    nodes = "".join(
        f"        - name: node-{node}\n"
        f"          ipv4: {IPV4_NETS[0][1 + ((index - 1) * args.nodes_per_location + node - 1) % 254]}\n"
        f"          ipv6: {IPV6_NET[(index - 1) * args.nodes_per_location + node]}\n"
        for node in range(1, args.nodes_per_location + 1)
    )
    return (
        "---\n"
        f"apiVersion: {API_VERSION}\n"
        "kind: Location\n"
        "metadata:\n"
        f"  name: {name}\n"
        f"  namespace: {args.namespace}\n"
        "  labels:\n"
        f"    {LABEL_KEY}: \"true\"\n"
        f"    zone: {zone_name}\n"
        f"    dnsendpoint: {endpoint_name}\n"
        f"    edgecdnx.com/routing-instance: {args.routing_instance}\n"
        "spec:\n"
        f"  weight: {weight}\n"
        "  nodeGroups:\n"
        "    - name: default\n"
        '      flavor: ""\n'
        "      nodes:\n"
        f"{nodes}"
    )


def geo_location_manifest(args, index, weight, zone_name, endpoint_name):
    if len(zone_name) > 63 or len(endpoint_name) > 63:
        raise ValueError("Geolocation zone and endpoint names must fit Kubernetes label values (63 characters)")
    groups = []
    for group in range(1, args.node_groups_per_location + 1):
        selected = group == args.node_groups_per_location
        group_label = "selected" if selected else "excluded"
        nodes = "".join(
            f"        - name: group-{group}-node-{node}\n"
            f"          ipv4: {IPV4_NETS[0][1 + ((index - 1) * args.node_groups_per_location * args.nodes_per_location + (group - 1) * args.nodes_per_location + node - 1) % 254]}\n"
            f"          ipv6: {IPV6_NET[(index - 1) * args.node_groups_per_location * args.nodes_per_location + (group - 1) * args.nodes_per_location + node]}\n"
            for node in range(1, args.nodes_per_location + 1)
        )
        groups.append(
            f"    - name: group-{group}\n"
            '      flavor: ""\n'
            "      labels:\n"
            f'        profiler.edgecdnx.com/node-group: "{group_label}"\n'
            "      nodes:\n"
            + nodes
        )
    value = args.geo_values[(index - 1) % len(args.geo_values)]
    return (
        "---\n"
        f"apiVersion: {API_VERSION}\n"
        "kind: Location\n"
        "metadata:\n"
        f"  name: {endpoint_name}-geo-{index:04d}\n"
        f"  namespace: {args.namespace}\n"
        "  labels:\n"
        f'    {LABEL_KEY}: "true"\n'
        f"    zone: {zone_name}\n"
        f"    dnsendpoint: {endpoint_name}\n"
        f"    edgecdnx.com/routing-instance: {args.routing_instance}\n"
        "spec:\n"
        "  geoLookup:\n"
        f"    weight: {weight}\n"
        "    attributes:\n"
        "      default:\n"
        "        weight: 1\n"
        f"      {json.dumps(args.geo_attribute)}:\n"
        "        weight: 100\n"
        "        values:\n"
        f"          - value: {json.dumps(value)}\n"
        f"            weight: {index}\n"
        "  nodeGroups:\n"
        + "".join(groups)
    )


def record_counts(args, rng):
    types = ("A", "AAAA") if getattr(args, "routing_policy", "Simple") in ("Weighted", "Geolocation") else RECORD_TYPES
    if not args.total:
        return {t: rng.randint(args.min_records, args.max_records) if t in types else 0
                for t in RECORD_TYPES}
    counts = {t: 0 for t in RECORD_TYPES}
    for _ in range(rng.randint(args.min_records, args.max_records)):
        counts[rng.choice(types)] += 1
    return counts


def generate(args, rng, stats, records=None, start=1):
    """Yield manifest documents, updating stats in place.

    Zones numbered below `start` are generated (so the random sequence stays identical
    for a given seed) but not emitted. Emitted records are appended to `records` as
    (fqdn, record_type) tuples when a list is supplied.
    """
    width = max(args.name_width, len(str(args.zones)))
    policy = getattr(args, "routing_policy", "Simple")
    for zi in range(1, args.zones + 1):
        emit = zi >= start
        zone_label = f"{args.zone_prefix}-{zi:0{width}d}"
        zone = f"{zone_label}.{args.zone_suffix}"
        if emit:
            yield zone_manifest(zone, zone, args.namespace)
            stats["zones"] += 1

        counts = record_counts(args, rng)
        a_hosts = []

        for rtype in ("A", "AAAA"):
            for ri in range(1, counts[rtype] + 1):
                host = f"{rtype.lower()}-{ri}"
                fqdn = f"{host}.{zone}"
                gen = random_ipv4 if rtype == "A" else random_ipv6
                targets = (sorted({gen(rng) for _ in range(rng.randint(1, args.max_targets))})
                           if policy == "Simple" else [])
                if rtype == "A":
                    a_hosts.append(fqdn)
                if not emit:
                    continue
                endpoint_name = f"{zone_label}-{host}"
                if policy in ("Weighted", "Geolocation"):
                    for index in range(1, args.locations_per_endpoint + 1):
                        weight = args.location_weights[(index - 1) % len(args.location_weights)]
                        manifest = geo_location_manifest if policy == "Geolocation" else location_manifest
                        yield manifest(args, index, weight, zone, endpoint_name)
                        stats["locations"] = stats.get("locations", 0) + 1
                yield endpoint_manifest(
                    endpoint_name, args.namespace, zone, fqdn, rtype, args.ttl, targets,
                    routing_policy=policy,
                )
                stats[rtype] += 1
                if records is not None:
                    records.append((fqdn, rtype))

        for ri in range(1, counts["CNAME"] + 1):
            host = f"cname-{ri}"
            fqdn = f"{host}.{zone}"
            # Prefer in-zone targets so lookups can be resolved by the plugin itself.
            target = rng.choice(a_hosts) if a_hosts else f"target-{ri}.example.com"
            if not emit:
                continue
            yield endpoint_manifest(
                f"{zone_label}-{host}", args.namespace, zone, fqdn, "CNAME", args.ttl, [f"{target}."]
            )
            stats["CNAME"] += 1
            if records is not None:
                records.append((fqdn, "CNAME"))


def kubectl(args, *cmd, stdin=None):
    base = ["kubectl"]
    if args.kubeconfig:
        base += ["--kubeconfig", args.kubeconfig]
    if args.context:
        base += ["--context", args.context]
    return subprocess.run(base + list(cmd), input=stdin, text=True, check=False).returncode


def main():
    args = parse_args()

    if args.delete:
        sys.exit(kubectl(args, "delete", "dnsendpoints,zones,locations", "-n", args.namespace,
                         "-l", f"{LABEL_KEY}=true"))

    rng = random.Random(args.seed)
    stats = {"zones": 0, **{t: 0 for t in RECORD_TYPES}}
    manifests = "".join(generate(args, rng, stats))

    if args.apply:
        rc = kubectl(args, "apply", "-f", "-", stdin=manifests)
        if rc != 0:
            sys.exit(rc)
    elif args.output:
        with open(args.output, "w") as f:
            f.write(manifests)
    else:
        sys.stdout.write(manifests)

    total = sum(stats[t] for t in RECORD_TYPES)
    print(
        f"Generated {stats['zones']} zones, {total} records "
        f"(A={stats['A']}, AAAA={stats['AAAA']}, CNAME={stats['CNAME']}), "
        f"{stats.get('locations', 0)} locations",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
